import { chromium } from '@playwright/test';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1050}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',msg=>{if(msg.type()==='error')console.log('browser warning',msg.text().slice(0,400));});
await page.goto('http://localhost:3000/design-preview',{waitUntil:'domcontentloaded'});
await page.waitForTimeout(1000);
await page.screenshot({path:'artifacts/marketplace-waterloo-desktop.png',fullPage:true});
console.log('heading',await page.locator('h1').evaluate(el=>({color:getComputedStyle(el).color,text:el.textContent,fontSize:getComputedStyle(el).fontSize})));
await page.goto('http://localhost:3000/design-preview?view=settings',{waitUntil:'domcontentloaded'});
console.log('settings',await page.locator('#notifications > div').boundingBox());
await page.waitForTimeout(1000);
await page.screenshot({path:'artifacts/notification-setting-desktop.png'});
await page.goto('http://localhost:3000/design-preview?view=sell',{waitUntil:'domcontentloaded'});
await page.waitForTimeout(1000);
await page.screenshot({path:'artifacts/sell-photos-desktop.png',fullPage:true});
await page.getByRole('button',{name:'Details',exact:true}).click();
await page.waitForTimeout(700);
await page.waitForTimeout(1000);
await page.screenshot({path:'artifacts/sell-details-desktop.png',fullPage:true});
await page.setViewportSize({width:390,height:844});
await page.goto('http://localhost:3000/design-preview',{waitUntil:'domcontentloaded'});
await page.waitForTimeout(1000);
await page.screenshot({path:'artifacts/marketplace-waterloo-mobile.png',fullPage:true});
console.log('mobile overflow',await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth));
await page.goto('http://localhost:3000/design-preview?view=settings',{waitUntil:'domcontentloaded'});
await page.waitForTimeout(1000);
await page.screenshot({path:'artifacts/notification-setting-mobile.png'});
console.log('errors',errors);
await browser.close();
